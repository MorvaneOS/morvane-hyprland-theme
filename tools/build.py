#!/usr/bin/env python3
"""Builds the MorvaneOS Hyprland theme.

    python tools/build.py

Needs only Python. Output goes to theme/ and skel/; commit it, it's what the package
installs.

Hyprland reads only ~/.config/hypr/hyprland.lua; without one, it copies its example
config there and warns that it's autogenerated. So new users get a hyprland.lua that
runs Hyprland's example config (/usr/share/hypr/hyprland.lua, from the hyprland
package) and then this theme, so both follow package updates, with room for their
own settings below. Later hl.config() calls override earlier ones.
"""

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INSTALLED = '/usr/share/morvane-hyprland-theme/theme.lua'
EXAMPLE = '/usr/share/hypr/hyprland.lua'

# Keep in step with the window colours in morvane-gtk-theme
PASTEL = 'f4a6c6'
LAVENDER = 'b9a3e6'
BORDER = '4a3552'  # a step lighter than the title bars: drawn over the wallpaper
NIGHT = '120c16'
URGENT = 'f0506e'
WALLPAPER = '/usr/share/backgrounds/morvaneos/twilight.png'

THEME = f'''\
-- MorvaneOS look for Hyprland: generated by tools/build.py in morvane-hyprland-theme,
-- edit that instead. Run after Hyprland's example config; later settings win.

hl.config({{
    general = {{
        col = {{
            -- The focused window's border runs Pastel Pink to Lavender; unfocused
            -- windows get a dim border, so focus isn't shown by hue alone
            active_border   = {{ colors = {{"rgba({PASTEL}ff)", "rgba({LAVENDER}ff)"}}, angle = 45 }},
            inactive_border = "rgba({BORDER}cc)",
        }},
    }},

    decoration = {{
        shadow = {{
            color = 0xee{NIGHT},
        }},
    }},

    misc = {{
        -- The MorvaneOS wallpaper instead of Hyprland's own
        force_default_wallpaper = 0,
        disable_hyprland_logo   = true,
        background_color        = 0xff{NIGHT},
    }},
}})

hl.on("hyprland.start", function ()
    hl.exec_cmd("swaybg -i {WALLPAPER} -m fill")
end)
'''

SKEL = f'''\
-- Your Hyprland config. It runs Hyprland's example config, then the MorvaneOS look
-- (from morvane-hyprland-theme); both follow package updates. Add your own settings
-- below: later settings override earlier ones. To start from a full copy instead,
-- replace these two lines with the contents of the two files.
dofile("{EXAMPLE}")
dofile("{INSTALLED}")
'''


def build() -> None:
	for folder in ('theme', 'skel'):
		shutil.rmtree(ROOT / folder, ignore_errors=True)
	(ROOT / 'theme').mkdir()
	(ROOT / 'theme' / 'theme.lua').write_text(THEME)
	(ROOT / 'skel').mkdir()
	(ROOT / 'skel' / 'hyprland.lua').write_text(SKEL)
	print('Built the Hyprland theme.')


if __name__ == '__main__':
	build()
